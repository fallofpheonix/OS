package audit

import (
	"encoding/json"
	"os"
)

func WriteJSONL(path string, v Violation) error {
	f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	defer func() {
		_ = f.Close()
	}()
	return json.NewEncoder(f).Encode(v)
}
